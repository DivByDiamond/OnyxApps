unsigned int gui_glyph8(unsigned char ch, int row) {
    unsigned int bits = 0;
    int c;
    if (ch < 0x20 || ch > 0x7E || row < 0 || row > 7) return 0;
    for (c = 0; c < 5; c++)
        if (cols[ch - 0x20][c] & (1u << row)) bits |= 1u << (4 - c);
    return bits;
}

/* 7-row variant for the widget raster (button labels): upper case only, so
 * descenders are never needed. */
unsigned int gui_glyph(unsigned char ch, int row) {
    if (ch >= 'a' && ch <= 'z') ch = (unsigned char)(ch - 32);
    return row > 6 ? 0 : gui_glyph8(ch, row);
}

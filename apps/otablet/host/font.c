unsigned int demo_glyph(unsigned char c, int row) {
    if (row < 0 || row > 6) return 0;
    if (c >= 'a' && c <= 'z') c -= 32;
    if (c >= 'A' && c <= 'Z') return letters[c - 'A'][row];
    if (c == '/') return 1u << row % 5;
    if (c == '-') return row == 3 ? 31 : 0;
    return 0;
}

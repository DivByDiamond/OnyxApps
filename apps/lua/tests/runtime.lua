local function group(name, f)
  local ok, err = pcall(f)
  assert(ok, name..': '..tostring(err))
  print('PASS '..name)
end
group('closures-recursion', function()
  local function counter(n) return function(d) n=n+d;return n end end
  local c=counter(4);assert(c(3)==7 and c(-2)==5)
  local function fact(n) if n<2 then return 1 end return n*fact(n-1) end
  assert(fact(10)==3628800)
  local total=0;for i=1,20 do if i%2==0 then total=total+i end end;assert(total==110)
end)
group('tables-metamethods', function()
  local a=setmetatable({v=3},{__add=function(x,y)return x.v+y.v end,__index=function(t,k)return k..'!' end,__len=function()return 7 end})
  assert(a+{v=4}==7 and a.missing=='missing!' and #a==7)
  local t={3,1,2};table.sort(t);assert(table.concat(t,',')=='1,2,3')
  table.move(t,1,3,2);assert(t[2]==1 and t[4]==3)
  local count=0;for k,v in pairs({a=1,b=2,c=3})do count=count+v end;assert(count==6)
end)
group('protected-errors', function()
  local ok,e=pcall(function()error('marker')end);assert(not ok and e:find('marker',1,true))
  local ok,e=xpcall(function()error('source')end,function(e)return 'handled' end);assert(not ok and e=='handled')
end)
group('coroutines', function()
  local co=coroutine.create(function(a)local b=coroutine.yield(a+1);return b*2 end)
  local ok,v=coroutine.resume(co,10);assert(ok and v==11)
  local ok,v=coroutine.resume(co,7);assert(ok and v==14 and coroutine.status(co)=='dead')
end)
group('gc-weak-finalizers', function()
  local finalized=0;local weak=setmetatable({},{__mode='v'})
  do local t=setmetatable({},{__gc=function()finalized=finalized+1 end});weak[1]=t end
  collectgarbage('collect');collectgarbage('collect');assert(weak[1]==nil and finalized==1)
end)
group('integer-numeric', function()
  assert((1<<62)==4611686018427387904)
  assert(((-1)>>1)==0x7fffffffffffffff)
  assert((0x123456789abcdef0 ~ 0xffff)==0x123456789abc210f)
  assert(-7//3==-3 and -7%3==2)
  assert(math.type(3)=='integer' and math.type(3.5)=='float')
  assert(tonumber('0x1.8p+2')==6)
end)
group('utf8-string-pack', function()
  local s=utf8.char(65,0x20ac,0x1f600);assert(utf8.len(s)==3)
  local a,b,c=utf8.codepoint(s,1,#s);assert(a==65 and b==0x20ac and c==0x1f600)
  local s=string.pack('<i8I4c3',-1234567890123,0xabcdef01,'xyz')
  local a,b,c,p=string.unpack('<i8I4c3',s);assert(a==-1234567890123 and b==0xabcdef01 and c=='xyz' and p==#s+1)
end)
group('file-io', function()
  local p=os.tmpname();local f=assert(io.open(p,'w+'))
  assert(f:write('alpha\nbeta\n'));assert(f:flush());assert(f:seek('set',0)==0)
  assert(f:read('l')=='alpha');assert(f:read('a')=='beta\n');assert(f:close());assert(os.remove(p))
  local f=assert(io.tmpfile());assert(f:write('abc'));assert(f:seek('set',0)==0);assert(f:read(3)=='abc');assert(f:close())
end)
group('require-lua', function()
  local p=os.tmpname(); local f=assert(io.open(p,'w'))
  assert(f:write('return {answer=42,inc=function(x)return x+1 end}'));assert(f:close())
  package.path=p
  local m=require('runtime_module');assert(m.answer==42 and m.inc(3)==4)
  assert(require('runtime_module')==m);assert(os.remove(p))
end)
group('load-dump', function()
  local f=assert(load('return function(x) return x*3+1 end','smoke','t'))()
  assert(f(7)==22)
  local b=string.dump(f);local g=assert(load(b,'binary','b'));assert(g(7)==22)
end)
